# 京东卡/购物卡/话费/充值卡 **不在** 口径内，不要扩宽（此前一度加入，已按用户要求回退）。
REAL_CASH = ("现金", "红包", "微信红包", "支付宝红包", "现金红包", "元红包", "现金券", "京东红包")
REAL_QB = ("Q币", "q币", "Q币券")
# 纯拉丁"QB/qb"必须独立成词（前后不能是字母数字）才算奖励词——
# 否则证据里 JS/CSS 残留的"qb"子串（如 nvwa 组件名 token "qb"）会误判 Q币
# （2026-09-12 实证：新天龙3周年证据里的组件名"qb"导致误判 real）。
_QB_LATIN = re.compile(r"(?<![A-Za-z0-9_])[Qq][Bb](?![A-Za-z0-9_])")
REAL_HW_DIRECT = ("键盘", "耳机")                 # 词本身足够区分，直接命中
REAL_HW_VERB = ("手机", "平板", "显卡", "显示器", "手表", "充电宝", "相机", "游戏机", "电竞椅")
_HW_RE = re.compile(r"[抽送赢领得抢攒][^。；，,\s]{0,10}?(" + "|".join(REAL_HW_VERB) + r")")

# —— 噪音词表（仅用于「为何排除」说明；核心判定只看 REAL_*）——
