def title_noise(title):
    """标题第一优先级噪音检查。命中返回命中的词，未命中返回 None。
    各渠道流程在抓规则正文【之前】先调这个：命中即终判噪音，不再抓正文。"""
    t = title or ""
    for w in TITLE_NOISE_FIRST:
        if w in t:
            return w
    # 游戏道具噪音：标题含实物硬件词时豁免（硬件是用户三类真奖励之一）
    if not any(w in t for w in REAL_HW_DIRECT + REAL_HW_VERB):
        for w in GAME_ITEM_NOISE:
            if w in t:
                return w
    return None


def reward_kind(title, summary=""):
    """返回 (kind, label)。
    kind='real' 时 label ∈ {'现金','Q币','实物硬件'}；
    kind='noise' 时 label=None。

    优先级（2026-09-12 用户口径）：
      1. 标题命中 TITLE_NOISE_FIRST → noise（不看 summary）；
      2. 否则在 标题+规则正文 里找现金/Q币/实物硬件证据 → real；
      3. 都没有 → noise。
    """
    t = title or ""
    # ── 第一优先级：标题噪音，直接终判 ──
    for w in TITLE_NOISE_FIRST:
        if w in t:
            return ("noise", None)
    # 游戏道具类噪音（带硬件豁免，逻辑与 title_noise 一致）：
    # 快爆流程只走 reward_kind 不单独调 title_noise，必须在此复检
    # （2026-09-12 实证：亲密玫瑰/专属称号/头像框/炫彩蛋·国王球四条漏杀）
    if not any(w in t for w in REAL_HW_DIRECT + REAL_HW_VERB):
        for w in GAME_ITEM_NOISE:
            if w in t:
                return ("noise", None)
    # ── 第二优先级：真奖励证据 = 活动规则/奖池正文（title 仅兜底参与匹配）──
    blob = "{} {}".format(t, summary or "")
    low = blob.lower()
    # Q币红包 / qb红包 装在 Q币 里（不是人民币现金），优先判 Q币
    if "q币红包" in low or "qb红包" in low:
        return ("real", "Q币")
    for k in REAL_CASH:
        if k.lower() in low:
            return ("real", "现金")
    for k in REAL_QB:
        if k.lower() in low:
            return ("real", "Q币")
    if _QB_LATIN.search(blob):
        return ("real", "Q币")
    for k in REAL_HW_DIRECT:
        if k in blob:
            return ("real", "实物硬件")
    if _HW_RE.search(blob):
        return ("real", "实物硬件")
    return ("noise", None)


def is_real_reward(title, summary=""):
    """便捷布尔：是否为真奖励（现金/Q币/实物硬件）。"""
    return reward_kind(title, summary)[0] == "real"


def matched_noise(title, summary=""):
    """返回命中的噪音词（用于解释为何排除），未命中返回 []。"""
    blob = "{} {}".format(title or "", summary or "")
    return [t for t in NOISE_TERMS if t in blob]
